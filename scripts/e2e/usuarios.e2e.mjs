// E2E: ABM de Usuarios (ADMIN) y Perfil del usuario logueado, contra el back real.
// - Crea usuarios e2e-<corrida>-…@clubimperio.com y los borra al final por SQL.
// - Edita el nombre del ADMIN logueado (para probar que la barra se actualiza) y lo restaura al final.
// - Nunca cambia la contraseña del ADMIN: con él solo se prueban validaciones y la "actual incorrecta".
import { config, sql } from './lib/config.mjs'
import { crearNavegador } from './lib/harness.mjs'

const b = await crearNavegador('/usuarios')
const { ok, paso, texto, esperar, input, campo, setInput, escribir, helper, boton, submit, irA, h1, filas, dialogo, client, red, login, session, elegir } = b

const CORRIDA = Date.now().toString(36)
const email = (nombre) => `e2e-${CORRIDA}-${nombre}@clubimperio.com`
const ANA = { nombre: 'Ana E2E', email: email('ana'), password: 'ClaveInicial1' }
const filaDe = (txt) => [...document.querySelectorAll('tbody tr')].find((tr) => tr.textContent.includes(txt))
const loginApi = (e, p) => client.api('/api/auth/login', { method: 'POST', body: { email: e, password: p }, auth: false }).then(() => 200, (err) => err.status)
let admin = null

try {
  await b.sesionAdmin()
  admin = session.loadSession().usuario

  paso('[1] Listado: el ADMIN se ve a sí mismo, sin poder desactivarse')
  await b.montarApp()
  ok(await esperar(() => document.querySelector('[aria-busy="true"]')), 'muestra el skeleton mientras carga')
  ok(await esperar(() => !!filaDe(admin.email)), 'muestra la tabla')
  const filaAdmin = filaDe(admin.email)
  ok(filaAdmin.textContent.includes('Vos') && filaAdmin.textContent.includes('ADMIN'), 'la fila propia tiene el chip "Vos" y el rol')
  const btnDesactivarme = filaAdmin.querySelector(`button[aria-label="Desactivar a ${admin.nombre}"]`)
  ok(btnDesactivarme?.disabled, 'el botón Desactivar propio está deshabilitado')
  ok(btnDesactivarme?.parentElement.getAttribute('aria-label')?.startsWith('No podés desactivar tu propio usuario'), `con la explicación: "${btnDesactivarme?.parentElement.getAttribute('aria-label')}"`)

  paso('[2] Alta: validaciones')
  boton('Nuevo usuario').click()
  ok(await esperar(() => location.pathname === '/usuarios/nuevo' && input('nombre')), 'botón "Nuevo usuario" → /usuarios/nuevo')
  submit()
  ok(await esperar(() => helper('nombre') === 'El nombre es obligatorio'), 'nombre obligatorio')
  ok(helper('email') === 'El email es obligatorio' && helper('rol') === 'Elegí el rol' && helper('password') === 'Mínimo 8 caracteres', 'email, rol y contraseña obligatorios')
  setInput('email', 'ana@')
  setInput('password', 'Corta12')
  submit()
  ok(await esperar(() => helper('email') === 'El email no es válido'), `email "ana@" → "${helper('email')}"`)
  ok(helper('password') === 'Mínimo 8 caracteres', 'contraseña de 7 → mínimo 8')
  setInput('password', 'ñ'.repeat(37)) // 37 letras pero 74 bytes: BCrypt solo acepta 72
  submit()
  ok(await esperar(() => helper('password').startsWith('Demasiado larga')), `37 "ñ" (74 bytes) → "${helper('password')}"`)
  setInput('password', ANA.password)
  setInput('confirmar', 'OtraCosa123')
  submit()
  ok(await esperar(() => helper('confirmar') === 'Las contraseñas no coinciden'), 'la confirmación no coincide → error en "Repetí la contraseña"')

  paso('[3] Alta válida')
  setInput('nombre', `  ${ANA.nombre}  `)
  setInput('email', ANA.email.toUpperCase())
  setInput('confirmar', ANA.password)
  await elegir('rol', 'USER')
  ok(input('rol').value === 'USER', 'rol elegido en el select')
  red.lenta()
  submit()
  const btn = () => document.querySelector('form button[type="submit"]')
  ok(await esperar(() => btn()?.textContent === 'Guardando...' && btn().disabled), 'botón "Guardando..." y deshabilitado')
  ok(await esperar(() => location.pathname === '/usuarios' && texto().includes(`Usuario creado: ${ANA.nombre} (USER)`)), 'toast "Usuario creado" y vuelve al listado')
  red.normal()
  ok(await esperar(() => !!filaDe(ANA.email)), `email guardado en minúsculas (${ANA.email})`)
  ok((await loginApi(ANA.email, ANA.password)) === 200, 'la usuaria nueva puede loguearse')
  const idAna = (await client.api('/api/usuarios')).find((u) => u.email === ANA.email).usuarioId

  paso('[4] Alta con email duplicado → error del back debajo del email')
  await irA('/usuarios/nuevo')
  await esperar(() => input('nombre')?.value === '')
  setInput('nombre', 'Otra')
  setInput('email', ANA.email)
  setInput('password', 'ClaveInicial1')
  setInput('confirmar', 'ClaveInicial1')
  await elegir('rol', 'USER')
  submit()
  ok(await esperar(() => helper('email') === `Ya existe un usuario con el email: ${ANA.email}`), `"${helper('email')}"`)

  paso('[5] Edición de otro usuario: nombre y rol')
  await irA('/usuarios')
  await esperar(() => filaDe(ANA.email))
  filaDe(ANA.email).click()
  ok(await esperar(() => location.pathname === `/usuarios/${idAna}/editar` && input('nombre')?.value === ANA.nombre), 'click en la fila → edición con sus datos')
  ok(!input('password') && !texto().includes('Este es tu usuario'), 'sin contraseña en el formulario y sin el aviso de "tu usuario"')
  ok(!document.querySelector('[role="combobox"][aria-disabled="true"]'), 'el rol de otro usuario sí se puede cambiar')
  setInput('nombre', 'Ana María E2E')
  await elegir('rol', 'ADMIN')
  submit()
  ok(await esperar(() => location.pathname === '/usuarios' && texto().includes('Cambios guardados')), 'toast "Cambios guardados"')
  ok(await esperar(() => filaDe(ANA.email)?.textContent.includes('Ana María E2E') && filaDe(ANA.email).textContent.includes('ADMIN')), 'el listado muestra el nombre y el rol nuevos')
  await client.api(`/api/usuarios/${idAna}`, { method: 'PUT', body: { rol: 'USER' } })

  paso('[6] Edición de uno mismo: rol y desactivación deshabilitados, con explicación')
  await irA(`/usuarios/${admin.usuarioId}/editar`)
  ok(await esperar(() => input('nombre')?.value === admin.nombre), 'carga los datos propios')
  ok(!!document.querySelector('[role="combobox"][aria-disabled="true"]'), 'el select de rol está deshabilitado')
  ok(helper('rol').startsWith('No podés quitarte el rol de ADMIN a vos mismo'), `explicación en el campo: "${helper('rol')}"`)
  ok(texto().includes('Este es tu usuario. No podés quitarte el rol de ADMIN ni desactivarte'), 'aviso visible (el tooltip no se ve en el celular)')
  ok(boton('Desactivar')?.disabled, 'botón Desactivar deshabilitado')
  ok(boton('Cambiar mi contraseña')?.getAttribute('href') === '/perfil', '"Cambiar mi contraseña" lleva a Mi perfil')
  setInput('nombre', `${admin.nombre} E2E`)
  submit()
  ok(await esperar(() => texto().includes(`${admin.nombre} E2E · ADMIN`)), 'la barra superior muestra el nombre nuevo sin volver a loguearse')
  ok(session.loadSession().usuario.nombre === `${admin.nombre} E2E`, 'la sesión guardada también se actualizó')
  await irA(`/usuarios/${admin.usuarioId}/editar`)
  await esperar(() => input('nombre')?.value === `${admin.nombre} E2E`)
  setInput('nombre', admin.nombre)
  submit()
  ok(await esperar(() => texto().includes(`${admin.nombre} · ADMIN`) && location.pathname === '/usuarios'), 'nombre restaurado')

  paso('[7] Cambiar la contraseña de otro usuario')
  await esperar(() => filaDe(ANA.email))
  filaDe(ANA.email).querySelector('button[aria-label^="Cambiar la contraseña"]').click()
  ok(await esperar(() => dialogo()?.textContent.includes(`Nueva contraseña para Ana María E2E (${ANA.email})`)), 'diálogo con el usuario elegido')
  setInput('password', 'NuevaClave123')
  setInput('confirmar', 'NuevaClave12')
  boton('Cambiar contraseña', dialogo()).click()
  ok(await esperar(() => helper('confirmar') === 'Las contraseñas no coinciden'), 'confirmación distinta → error')
  setInput('confirmar', 'NuevaClave123')
  boton('Cambiar contraseña', dialogo()).click()
  ok(await esperar(() => !dialogo() && texto().includes('Se cambió la contraseña de Ana María E2E')), 'toast y se cierra el diálogo')
  ok((await loginApi(ANA.email, 'NuevaClave123')) === 200 && (await loginApi(ANA.email, ANA.password)) === 401, 'entra con la nueva y ya no con la anterior')
  filaDe(admin.email).querySelector('button[aria-label^="Cambiar la contraseña"]').click()
  ok(await esperar(() => location.pathname === '/perfil'), 'la llave de la fila propia lleva a Mi perfil (no resetea sin pedir la actual)')

  paso('[8] Desactivar y reactivar')
  await irA('/usuarios')
  await esperar(() => filaDe(ANA.email))
  filaDe(ANA.email).querySelector('button[aria-label^="Desactivar"]').click()
  ok(await esperar(() => dialogo()?.textContent.includes('¿Desactivar a Ana María E2E') && dialogo().textContent.includes('Ya no va a poder iniciar sesión')), 'modal de confirmación')
  red.lenta()
  boton('Desactivar', dialogo()).click()
  ok(await esperar(() => boton('Desactivando...', dialogo())?.disabled), 'botón "Desactivando..." deshabilitado')
  ok(await esperar(() => !dialogo() && texto().includes('Se desactivó a Ana María E2E')), 'toast "Se desactivó"')
  red.normal()
  ok(await esperar(() => !filaDe(ANA.email)), 'con el filtro "Activos" desaparece')
  ok((await loginApi(ANA.email, 'NuevaClave123')) === 401, 'ya no puede loguearse')
  await irA('/usuarios?estado=inactivos')
  ok(await esperar(() => filaDe(ANA.email)?.textContent.includes('Inactivo')), 'con "Inactivos" aparece')
  filaDe(ANA.email).querySelector('button[aria-label^="Reactivar"]').click()
  ok(await esperar(() => texto().includes('Se reactivó a Ana María E2E') && !filaDe(ANA.email)), 'Reactivar → toast y sale de "Inactivos"')
  ok((await loginApi(ANA.email, 'NuevaClave123')) === 200, 'vuelve a poder loguearse')

  paso('[9] Filtros')
  await irA('/usuarios?rol=ADMIN')
  ok(await esperar(() => !!filaDe(admin.email) && !filaDe(ANA.email)), 'rol ADMIN → no aparece Ana (USER)')
  await irA('/usuarios')
  await esperar(() => filaDe(admin.email))
  escribir(campo('Buscar por nombre o email'), `e2e-${CORRIDA}`)
  ok(await esperar(() => filas() === 1 && !!filaDe(ANA.email)), 'búsqueda por email → 1 resultado')

  paso('[10] Mi perfil (ADMIN): datos y validaciones, sin cambiar su contraseña')
  document.querySelector('a[href="/perfil"]').click()
  ok(await esperar(() => location.pathname === '/perfil' && h1() === 'Mi perfil'), 'el nombre de la barra superior lleva a Mi perfil')
  ok(await esperar(() => texto().includes(admin.email) && texto().includes('Usuario desde')), 'muestra los datos (de /api/auth/me)')
  submit()
  ok(await esperar(() => helper('passwordActual') === 'Ingresá tu contraseña actual' && helper('passwordNueva') === 'Mínimo 8 caracteres'), 'actual y nueva obligatorias')
  setInput('passwordActual', 'MismaClave123')
  setInput('passwordNueva', 'MismaClave123')
  setInput('confirmar', 'MismaClave123')
  submit()
  ok(await esperar(() => helper('passwordNueva') === 'Tiene que ser distinta de la actual'), 'nueva igual a la actual → error (antes de ir al back)')
  setInput('passwordActual', 'NoEsLaClave1')
  setInput('passwordNueva', 'OtraClave456')
  setInput('confirmar', 'OtraClave456')
  submit()
  ok(await esperar(() => helper('passwordActual') === 'La contraseña actual es incorrecta.'), `actual incorrecta → error del back en el campo: "${helper('passwordActual')}"`)
  ok(location.pathname === '/perfil' && !!session.getToken(), 'el 400 no cierra la sesión')
  ok((await loginApi(config.admin.email, config.admin.password)) === 200, 'la contraseña del ADMIN no cambió')

  paso('[11] Mi perfil (USER): cambio de la propia contraseña')
  document.querySelector('button[aria-label="Cerrar sesión"]').click()
  await esperar(() => location.pathname === '/login')
  await login({ email: ANA.email, password: 'NuevaClave123' })
  ok(await esperar(() => texto().includes('Ana María E2E · USER')), 'login de la USER')
  await irA('/perfil')
  ok(await esperar(() => texto().includes(ANA.email) && texto().includes('USER')), 'su perfil, con rol USER')
  setInput('passwordActual', 'NuevaClave123')
  setInput('passwordNueva', 'OtraClave456')
  setInput('confirmar', 'OtraClave456')
  red.lenta()
  submit()
  ok(await esperar(() => btn()?.textContent === 'Guardando...' && btn().disabled), 'botón "Guardando..." y deshabilitado')
  ok(await esperar(() => texto().includes('Contraseña actualizada')), 'toast "Contraseña actualizada"')
  red.normal()
  ok(await esperar(() => input('passwordActual').value === '' && input('passwordNueva').value === ''), 'el formulario queda vacío (no deja contraseñas escritas)')
  ok((await loginApi(ANA.email, 'OtraClave456')) === 200 && (await loginApi(ANA.email, 'NuevaClave123')) === 401, 'entra con la nueva y ya no con la anterior')
  await irA('/usuarios')
  ok(await esperar(() => texto().includes('No tenés permisos para ver esta pantalla.')), 'como USER, /usuarios → sin permisos')

  paso('[12] Links inválidos (como ADMIN)')
  document.querySelector('button[aria-label="Cerrar sesión"]').click()
  await esperar(() => location.pathname === '/login')
  await login(config.admin)
  await esperar(() => texto().includes('· ADMIN'))
  await irA('/usuarios/abc/editar')
  ok(await esperar(() => texto().includes('No existe el usuario') && texto().includes('El link no es válido.')), '/usuarios/abc/editar → "No existe el usuario"')
  await irA('/usuarios/00000000-0000-0000-0000-000000000000/editar')
  ok(await esperar(() => texto().includes('No se encontró el usuario.')), 'UUID inexistente → mensaje del back')
  ok(!boton('Reintentar') && !!boton('Volver al listado'), 'sin "Reintentar", con "Volver al listado"')
  b.sinErroresDeReact()
} catch (e) {
  b.fallar(e.stack ?? e)
} finally {
  red.normal()
  try {
    // El nombre del ADMIN vuelve a como estaba, pase lo que pase en la prueba
    if (admin) {
      await b.sesionAdmin()
      const actual = await client.api(`/api/usuarios/${admin.usuarioId}`)
      if (actual.nombre !== admin.nombre) await client.api(`/api/usuarios/${admin.usuarioId}`, { method: 'PUT', body: { nombre: admin.nombre } })
    }
    // Borrado físico de los usuarios de esta corrida. Doble condición: prefijo e2e- y el id de la corrida.
    const [[borrados]] = sql(`WITH d AS (DELETE FROM usuarios WHERE email LIKE 'e2e-${CORRIDA}-%@clubimperio.com' RETURNING 1) SELECT count(*) FROM d;`)
    const [[restantes]] = sql(`SELECT count(*) FROM usuarios WHERE email LIKE 'e2e-${CORRIDA}-%';`)
    console.log(`\n[limpieza] ${borrados} usuarios borrados; quedan ${restantes}; nombre del ADMIN restaurado`)
    if (restantes !== '0') b.fallar('la limpieza dejó usuarios de prueba')
  } catch (e) {
    b.fallar(`limpieza: ${e.message}`)
  }
  await b.terminar()
}
